import { launch, sleep } from './harness.mjs'
const out = process.argv[2] || '/tmp'
const { browser, page, errors } = await launch({ url: 'http://localhost:5173/?debug&dpr=0.5', quality: 'low', width: 1280, height: 720 })
await sleep(1500)
await page.screenshot({ path: `${out}/ui_splash.png` })
await page.click('.splash')
await sleep(2500)
await page.screenshot({ path: `${out}/ui_menu_loading.png` })
await page.waitForFunction(() => window.__DLA?.game.getState().assetsReady === true, null, { timeout: 240000 })
await sleep(1000)
await page.screenshot({ path: `${out}/ui_menu.png` })
await page.click('text=SETTINGS')
await sleep(1200)
await page.screenshot({ path: `${out}/ui_settings.png` })
await page.click('text=BACK')
await sleep(600)
await page.click('text=CREDITS')
await sleep(1200)
await page.screenshot({ path: `${out}/ui_credits.png` })
await page.click('text=BACK')
await page.setViewportSize({ width: 390, height: 844 })
await sleep(1200)
await page.screenshot({ path: `${out}/ui_menu_mobile.png` })
console.log(errors.join('\n'))
await browser.close()
