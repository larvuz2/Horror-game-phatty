import { launch, enterGame, state, sleep, lookAt } from './harness.mjs'
const out = process.argv[2] || '/tmp'
const { browser, page, errors } = await launch({ quality: process.env.Q || 'medium' })
await page.screenshot({ path: `${out}/s0_splash.png` })
await page.click('.splash')
await page.waitForFunction(() => window.__DLA?.game.getState().assetsReady === true, null, { timeout: 240000 })
await sleep(500)
await page.screenshot({ path: `${out}/s1_menu.png` })
await page.click('text=START')
await page.waitForFunction(() => window.__DLA.game.getState().phase === 'PLAYING', null, { timeout: 120000 })
await sleep(1500)
console.log(JSON.stringify(await state(page)))
await page.screenshot({ path: `${out}/s2_start.png` })
await lookAt(page, 1.9, 5.7, -0.35)
await sleep(1500)
await page.screenshot({ path: `${out}/s3_table.png` })
console.log(JSON.stringify(await state(page)))
console.log('ERRORS:\n' + errors.join('\n'))
await browser.close()
